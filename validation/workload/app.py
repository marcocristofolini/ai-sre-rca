from __future__ import annotations

import json
import os
import threading
import time
import urllib.request
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from opentelemetry import trace
from opentelemetry.exporter.otlp.proto.http.trace_exporter import OTLPSpanExporter
from opentelemetry.sdk.resources import Resource
from opentelemetry.sdk.trace import TracerProvider
from opentelemetry.sdk.trace.export import SimpleSpanProcessor
from opentelemetry.trace import SpanKind, Status, StatusCode

SERVICE = "frontend"
POD_NAME = os.getenv("POD_NAME", "rc2-workload")
LOKI_URL = os.getenv("LOKI_URL", "http://loki:3100/loki/api/v1/push")
TEMPO_URL = os.getenv("TEMPO_URL", "http://tempo:4318/v1/traces")
PORT = int(os.getenv("PORT", "8080"))

provider = TracerProvider(
    resource=Resource.create(
        {
            "service.name": SERVICE,
            "service.version": "rc2",
            "deployment.environment.name": "validation",
            "k8s.namespace.name": "rca-validation",
            "k8s.deployment.name": "rc2-workload",
        }
    )
)
provider.add_span_processor(
    SimpleSpanProcessor(
        OTLPSpanExporter(
            endpoint=TEMPO_URL,
            timeout=5,
        )
    )
)
trace.set_tracer_provider(provider)
tracer = trace.get_tracer("ai-sre-rc2-validation")

_lock = threading.Lock()
_requests = 0
_failures = 0
_postgres_pressure = False
POSTGRES_INSTANCE = "orders-db:5432"
POSTGRES_DATABASE = "orders"


def _post_json(url: str, payload: dict) -> None:
    request = urllib.request.Request(
        url,
        data=json.dumps(payload).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=5) as response:
        if response.status >= 300:
            raise RuntimeError(f"POST {url} returned {response.status}")


def emit_log(trace_id: str) -> None:
    payload = {
        "streams": [
            {
                "stream": {
                    "namespace": "rca-validation",
                    "pod": POD_NAME,
                    "app": SERVICE,
                    "level": "error",
                },
                "values": [
                    [
                        str(time.time_ns()),
                        (
                            f"checkout failed trace_id={trace_id} "
                            "dependency=orders-db error=connection_refused"
                        ),
                    ]
                ],
            }
        ]
    }
    _post_json(LOKI_URL, payload)


def emit_failure_trace() -> str:
    with tracer.start_as_current_span(
        "GET /checkout",
        kind=SpanKind.SERVER,
        attributes={
            "http.request.method": "GET",
            "http.response.status_code": 500,
        },
    ) as root:
        trace_id = f"{root.get_span_context().trace_id:032x}"
        with tracer.start_as_current_span(
            "SELECT orders",
            kind=SpanKind.CLIENT,
            attributes={
                "db.system": "postgresql",
                "db.namespace": "orders",
                "server.address": "orders-db",
                "server.port": 5432,
                "error.type": "connection_refused",
            },
        ) as child:
            child.set_status(Status(StatusCode.ERROR, "connection refused"))
            time.sleep(0.05)
        root.set_status(Status(StatusCode.ERROR, "downstream database failure"))
    return trace_id


