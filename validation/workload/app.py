class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt: str, *args) -> None:
        return

    def _send(self, status: int, body: bytes, content_type: str = "text/plain") -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self) -> None:
        global _requests, _failures, _postgres_pressure
        if self.path == "/health":
            self._send(200, b"ok\n")
            return
        if self.path == "/metrics":
            self._send(200, metrics().encode(), "text/plain; version=0.0.4")
            return
        if self.path == "/stateful/postgres/critical":
            with _lock:
                _postgres_pressure = True
            self._send(200, b"postgres pressure enabled\n")
            return
        if self.path == "/stateful/postgres/recover":
            with _lock:
                _postgres_pressure = False
            self._send(200, b"postgres pressure cleared\n")
            return
        if self.path == "/fail":
            with _lock:
                _requests += 1
                _failures += 1
            try:
                trace_id = emit_failure_trace()
                emit_log(trace_id)
            except Exception as exc:
                self._send(503, f"telemetry emission failed: {exc}\n".encode())
                return
            self._send(500, f"dependency failure trace_id={trace_id}\n".encode())
            return
        self._send(404, b"not found\n")


if __name__ == "__main__":
    ThreadingHTTPServer(("0.0.0.0", PORT), Handler).serve_forever()
