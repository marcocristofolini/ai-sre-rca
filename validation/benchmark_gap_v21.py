"""Post-execution gap comparison; never imported by an investigation engine."""
import argparse
from collections import Counter
import json
from pathlib import Path

from validation.benchmark_v2 import fingerprint, validate_result
from app.schemas import InvestigationResult

ROOT = Path(__file__).resolve().parents[1]

# Ground truth is consulted only here, after all predictions are written.
ABSTENTIONS = {
    'b001': ('correct_abstention', 'Healthy runtime; temporal deployment proximity is not causation.'),
    'b004': ('unsupported_investigation', 'Missing Pod state; abstention is correct, investigation lacks causal coverage.'),
    'b005': ('correct_abstention', 'Recovered current runtime; historical OOM log is outside the selected window.'),
    'b006': ('correct_abstention', 'Different origins in two traces; required repeated-origin gate is unsatisfied.'),
    'b008': ('correct_abstention', 'Healthy runtime; malicious instructions are untrusted data, not evidence.'),
    'l001': ('correct_abstention', 'Healthy real rollout and HTTP 200 observations.'),
    'l003': ('correct_abstention', 'Recovered revision and fresh telemetry identity with HTTP 200 observations.'),
    'l004': ('correct_abstention', 'Healthy pilot observations; original errors were source-planning failures.'),
}
PARTIALS = {
    ('b002', 'classic'): 'OOM playbook selects container-oom; node-not-ready is not generated by this Pod playbook.',
    ('b002', 'agentic'): 'Shared Kubernetes stage uses the OOM playbook; node-not-ready candidate is absent.',
    ('b002', 'copilot'): 'Same deterministic evaluator and missing node-not-ready candidate as agentic.',
    ('l002', 'classic'): 'Classic Kubernetes stage lacks controller-scope expansion; Pod is unset and trace propagation wins.',
    ('l002', 'agentic'): 'Trace candidate satisfies repeated-origin gate but direct OOM evidence blocks downstream promotion.',
    ('l002', 'copilot'): 'Same direct-Kubernetes precedence gate as agentic; no independent multi-root selection contract.',
}


def outcome(row):
    if row['error'] is not None:
        return 'error'
    if row['rejected_status'] is not None:
        return 'rejected' if row['correct_rejection'] else 'incorrect'
    if row['partial_diagnosis']:
        return 'partial'
    if row['predicted_hypothesis'] is None:
        return 'inconclusive'
    return 'complete' if row['correct'] else 'incorrect'


def compare_reports(baseline, repaired):
    comparisons, classifications = [], []
    if set(baseline['groups']) != set(repaired):
        raise ValueError('dataset coverage mismatch')
    for group, old in baseline['groups'].items():
        new = repaired[group]
        before = {(r['case'], r['engine']): r for r in old['results']}
        after = {(r['case'], r['engine']): r for r in new['results']}
        if len(before) != len(old['results']) or len(after) != len(new['results']) or before.keys() != after.keys():
            raise ValueError('case/path coverage mismatch')
        for key, prior in before.items():
            current = after[key]
            if current['expected_causes'] != prior['expected_causes']:
                raise ValueError('ground truth changed')
            diagnosis = InvestigationResult.model_validate(current['diagnosis']) if current.get('diagnosis') else None
            if diagnosis:
                validate_result(diagnosis)
                if not set(current['citations']) <= {e.id for e in diagnosis.evidence}:
                    raise ValueError('foreign citation')
            entry = {'dataset':group, 'case':key[0], 'engine':key[1],
                     'expected_causes':prior['expected_causes'],
                     'before': {k:prior[k] for k in ('predicted_hypothesis','latency_seconds','telemetry_query_count','error','integrity_ok')},
                     'after': {k:current[k] for k in ('predicted_hypothesis','latency_seconds','telemetry_query_count','error','integrity_ok')},
                     'before_outcome':outcome(prior), 'after_outcome':outcome(current),
                     'unreported_causes':current['unreported_causes'],
                     'false_confirmation':current['false_confirmation'],
                     'citations_verified':diagnosis is not None,
                     'query_budget':diagnosis.query_budget if diagnosis else None}
            if prior['partial_diagnosis']:
                entry['gap_analysis'] = PARTIALS[key]
                if diagnosis and diagnosis.agentic:
                    entry['hypothesis_gates'] = [n for n in diagnosis.agentic.explanation_graph['nodes']
                                               if n['kind'] == 'hypothesis']
            if outcome(prior) == 'inconclusive':
                category, reason = ABSTENTIONS[key[0]]
                # No abstention may be called correct when the oracle expects a cause.
                if prior['expected_causes'] or not prior['correct_abstention']:
                    category, reason = 'coverage_gap', 'Oracle expects a cause not returned by this path.'
                classifications.append({'case':key[0], 'engine':key[1], 'classification':category,
                                        'oracle_correct_abstention':prior['correct_abstention'], 'reason':reason})
            comparisons.append(entry)
    return {'benchmark_version':'2.1', 'base_commit':'1fb1e2f',
            'baseline_digest':fingerprint(baseline),
            'before_counts':{name:sum(r['before_outcome'] == name for r in comparisons)
                            for name in ('complete','partial','incorrect','inconclusive','rejected','error')},
            'after_counts':{name:sum(r['after_outcome'] == name for r in comparisons)
                            for name in ('complete','partial','incorrect','inconclusive','rejected','error')},
            'false_confirmations':sum(r['false_confirmation'] for r in comparisons),
            'integrity_passed':sum(r['after']['integrity_ok'] is True for r in comparisons),
            'classification_counts':dict(Counter(r['classification'] for r in classifications)),
            'baseline_inconclusive_classification':classifications, 'comparisons':comparisons,
            'metrics':{g:r['metrics'] for g,r in repaired.items()},
            'telemetry_query_count_before':sum(r['before']['telemetry_query_count'] for r in comparisons),
            'telemetry_query_count_after':sum(r['after']['telemetry_query_count'] for r in comparisons),
            'model_tokens':0,'model_cost_usd':0,'telemetry_cost_usd':None,'infrastructure_cost_usd':None,
            'fresh_live_source_errors':repaired['live']['source_errors'],
            'legacy_capture_source_errors_retained':repaired['legacy_capture']['source_errors'],
            'live_regressions_passed':repaired['live']['metadata']['regressions']['passed'],
            'passed':all(r['passed'] for r in repaired.values()),
            'limits':['Unchanged single-root contracts and causal precedence still fail complete multi-cause scoring.',
                      'Ground truth is runtime-blinded and self-authored, not externally adjudicated.',
                      'Live before/after use equivalent protocols but fresh identities and times, not identical observations.',
                      'Latency is frozen-response execution; error trials are excluded from path percentiles.',
                      'Historical capture retains original optional-source failures; it cannot prove current source health.']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--synthetic', type=Path, required=True)
    parser.add_argument('--live', type=Path, required=True)
    parser.add_argument('--legacy', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    baseline = json.loads((ROOT/'docs/benchmarks/rca-v2-local.json').read_text())
    repaired = {key:json.loads(path.read_text()) for key,path in
                [('synthetic',args.synthetic),('live',args.live),('legacy_capture',args.legacy)]}
    report = compare_reports(baseline,repaired)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report,indent=2,sort_keys=True)+'\n')
    lines = ['# RCA Benchmark v2.1 — case comparison', '',
             'Strict complete-cause benchmark: '+('PASS' if report['passed'] else 'FAIL'), '',
             '| Case | Path | Before | After | Missing causes |', '| --- | --- | --- | --- | --- |']
    for row in report['comparisons']:
        lines.append(f"| {row['case']} | {row['engine']} | {row['before_outcome']} | {row['after_outcome']} | {', '.join(row['unreported_causes']) or '—'} |")
    lines += ['', '## Baseline inconclusive classification', '']
    for row in report['baseline_inconclusive_classification']:
        lines.append(f"- {row['case']}/{row['engine']}: {row['classification']}; {row['reason']}")
    lines += ['', '## Partial diagnoses', '']
    for row in report['comparisons']:
        if row.get('gap_analysis'):
            lines.append(f"- {row['case']}/{row['engine']}: {row['gap_analysis']}")
    lines += ['', '## Limits', ''] + ['- '+v for v in report['limits']]
    args.output.with_suffix('.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps({k:report[k] for k in ('before_counts','after_counts','false_confirmations','integrity_passed','passed')}))
    return int(not report['passed'])


if __name__ == '__main__':
    raise SystemExit(main())
